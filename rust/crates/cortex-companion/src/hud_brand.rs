use ratatui::buffer::Buffer;
use ratatui::layout::Rect;
use ratatui::prelude::Color;

fn rgb(v: u32) -> Option<Color> {
    if v == 0 {
        None
    } else {
        Some(Color::Rgb(
            ((v >> 16) & 0xFF) as u8,
            ((v >> 8) & 0xFF) as u8,
            (v & 0xFF) as u8,
        ))
    }
}

fn pix(data: &[u32], w: usize, x: usize, y: usize) -> u32 {
    if x >= w {
        0
    } else {
        let i = y * w + x;
        if i < data.len() {
            data[i]
        } else {
            0
        }
    }
}

/// Fondo del HUD: los transparentes no se pintan (se ve este color del pane).
/// Catppuccin Mocha base, alineado al chrome del rediseño.
pub const CELL_BG: Color = Color::Rgb(0x1E, 0x1E, 0x2E);

fn paint_cell(buf: &mut Buffer, x: u16, y: u16, top: Option<Color>, bot: Option<Color>) {
    let Some(cell) = buf.cell_mut((x, y)) else {
        return;
    };
    match (top, bot) {
        (None, None) => {}
        (Some(t), None) => {
            cell.set_symbol("▀");
            cell.set_fg(t);
            cell.set_bg(CELL_BG);
        }
        (None, Some(b)) => {
            cell.set_symbol("▄");
            cell.set_fg(b);
            cell.set_bg(CELL_BG);
        }
        (Some(t), Some(b)) if t == b => {
            cell.set_symbol("█");
            cell.set_fg(t);
            cell.set_bg(CELL_BG);
        }
        (Some(t), Some(b)) => {
            cell.set_symbol("▀");
            cell.set_fg(t);
            cell.set_bg(b);
        }
    }
}

#[derive(Clone, Copy, PartialEq, Eq, Debug, Default)]
pub enum MarkRam {
    #[default]
    Idle,
    WeakAwake,
    Awake,
}

pub fn tone(v: u32, ram: MarkRam) -> u32 {
    if v == 0 {
        return 0;
    }
    let factor = match ram {
        MarkRam::Idle => 0.72,
        MarkRam::WeakAwake => 0.88,
        MarkRam::Awake => 1.0,
    };
    let r = (((v >> 16) & 0xFF) as f64 * factor) as u32;
    let g = (((v >> 8) & 0xFF) as f64 * factor) as u32;
    let b = ((v & 0xFF) as f64 * factor) as u32;
    (r << 16) | (g << 8) | b
}

/// Pinta una grilla voxel con half-blocks. Recorta a `area`. No pinta transparentes.
pub fn blit(buf: &mut Buffer, area: Rect, data: &[u32], w: usize, h: usize) {
    let rows = h.div_ceil(2).min(area.height as usize);
    let cols = w.min(area.width as usize);
    for cy in 0..rows {
        let py = cy * 2;
        for cx in 0..cols {
            let top = rgb(pix(data, w, cx, py));
            let bot = if py + 1 < h {
                rgb(pix(data, w, cx, py + 1))
            } else {
                None
            };
            paint_cell(buf, area.x + cx as u16, area.y + cy as u16, top, bot);
        }
    }
}

pub fn blit_mark(buf: &mut Buffer, area: Rect, ram: MarkRam) {
    let rows = MARK_H.div_ceil(2).min(area.height as usize);
    let cols = MARK_W.min(area.width as usize);
    for cy in 0..rows {
        let py = cy * 2;
        for cx in 0..cols {
            let top = rgb(tone(pix(&MARK, MARK_W, cx, py), ram));
            let bot = if py + 1 < MARK_H {
                rgb(tone(pix(&MARK, MARK_W, cx, py + 1), ram))
            } else {
                None
            };
            paint_cell(buf, area.x + cx as u16, area.y + cy as u16, top, bot);
        }
    }
}

pub fn blit_word(buf: &mut Buffer, area: Rect) {
    blit(buf, area, &WORD, WORD_W, WORD_H);
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn dims() {
        assert_eq!(MARK.len(), MARK_W * MARK_H);
        assert_eq!(WORD.len(), WORD_W * WORD_H);
    }

    #[test]
    fn mark_tiene_tinta() {
        let ink = MARK.iter().filter(|c| **c != 0).count();
        assert!(ink > 150, "isotipo demasiado vacío: {ink}");
        assert!(MARK.contains(&TOP) || MARK.contains(&MINT_PALE) || MARK.contains(&FOREST));
        // El wordmark del HUD usa la paleta fría del rediseño (sky/ice/zafiro/navy).
        assert!(WORD.contains(&0x89DCEB));
    }

    #[test]
    fn sin_neon() {
        for c in MARK.iter().chain(WORD.iter()) {
            assert_ne!(*c, 0x34D399);
            assert_ne!(*c, 0x10B981);
        }
    }

    #[test]
    fn ram_tones_darken_idle() {
        let original = 0xE4EDE7;
        let awake = tone(original, MarkRam::Awake);
        let weak = tone(original, MarkRam::WeakAwake);
        let idle = tone(original, MarkRam::Idle);
        assert_eq!(awake, original);
        assert!(weak < awake);
        assert!(idle < weak);
    }
}
