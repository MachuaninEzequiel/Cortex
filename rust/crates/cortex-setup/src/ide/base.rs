/// `json.dumps(data, indent=2)` (ensure_ascii=True por defecto en Python:
/// escapa no-ASCII como \uXXXX).
pub fn json_dump_ascii(value: &Value) -> String {
    let pretty = serde_json::to_string_pretty(value).expect("JSON serializable");
    escape_non_ascii(&pretty)
}

/// `json.dumps(data, indent=2, ensure_ascii=False)`.
pub fn json_dump_utf8(value: &Value) -> String {
    serde_json::to_string_pretty(value).expect("JSON serializable")
}

fn escape_non_ascii(s: &str) -> String {
    let mut out = String::with_capacity(s.len());
    for ch in s.chars() {
        let cp = ch as u32;
        if cp > 0x7E {
            if cp > 0xFFFF {
                // Python json usa pares surrogate \udXXX\udXXX (hex lowercase).
                let v = cp - 0x10000;
                let hi = 0xD800 + (v >> 10);
                let lo = 0xDC00 + (v & 0x3FF);
                out.push_str(&format!("\\u{hi:04x}\\u{lo:04x}"));
            } else {
                out.push_str(&format!("\\u{cp:04x}"));
            }
        } else {
            out.push(ch);
        }
    }
    out
}

