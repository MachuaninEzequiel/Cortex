use std::path::{Path, PathBuf};

use serde_json::Value;

use super::IdeCtx;

pub const CORTEX_MARKER_OPEN: &str = "<!-- BEGIN CORTEX SECTION (auto-generated, do not edit) -->";
pub const CORTEX_MARKER_CLOSE: &str = "<!-- END CORTEX SECTION -->";

/// `_generate_autogen_header`: el string empieza con `\n` igual que Python.
pub fn generate_autogen_header(ctx: &IdeCtx, sources: &[&str], ide_name: &str) -> String {
    // datetime.now().strftime("%Y-%m-%dT%H:%M:%SZ") en hora LOCAL del
    // proceso; los fixtures congelan `now` ya en hora local deseada.
    let timestamp = ctx.now.format("%Y-%m-%dT%H:%M:%SZ");
    let sources_str = sources.join(", ");
    format!(
        "\n⚠️ AUTOGENERATED BY CORTEX - DO NOT EDIT MANUALLY\n\
         Source: {sources_str}\n\
         Last sync: {timestamp}\n\
         Regenerate: cortex sync-ide --ide {ide_name} --force\n"
    )
}

/// `_backup_file`: copia `<name>.cortex_backup_%Y%m%d_%H%M%S` si existe.
/// Devuelve la ruta de backup (o la original si no había nada que respaldar).
pub fn backup_file(ctx: &IdeCtx, file_path: &Path) -> PathBuf {
    if !file_path.exists() {
        return file_path.to_path_buf();
    }
    let timestamp = ctx.now.format("%Y%m%d_%H%M%S");
    let name = file_path.file_name().unwrap_or_default().to_string_lossy();
    let backup = file_path
        .parent()
        .unwrap_or(Path::new("."))
        .join(format!("{name}.cortex_backup_{timestamp}"));
    let _ = std::fs::copy(file_path, &backup);
    backup
}

/// `_deep_merge_dict` sobre serde_json Values (solo objetos se fusionan).
pub fn deep_merge_dict(base: &Value, update: &Value) -> Value {
    match (base, update) {
        (Value::Object(b), Value::Object(u)) => {
            let mut result = b.clone();
            for (k, v) in u {
                match result.get(k) {
                    Some(existing) if existing.is_object() && v.is_object() => {
                        result.insert(k.clone(), deep_merge_dict(existing, v));
                    }
                    _ => {
                        result.insert(k.clone(), v.clone());
                    }
                }
            }
            Value::Object(result)
        }
        (_, update) => update.clone(),
    }
}

/// `_append_to_markdown`.
pub fn append_to_markdown(file_path: &Path, content: &str, separator: &str) -> std::io::Result<()> {
    if file_path.exists() {
        let existing = std::fs::read_to_string(file_path)?;
        if existing.contains(content.trim()) {
            return Ok(());
        }
        std::fs::write(file_path, format!("{existing}{separator}{content}"))
    } else {
        std::fs::write(file_path, content)
    }
}

