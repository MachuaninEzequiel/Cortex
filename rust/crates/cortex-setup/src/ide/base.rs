/// True si `content` contiene al menos un bloque entre marcadores.
pub fn has_marker_block(content: &str) -> bool {
    has_marker_block_with(content, CORTEX_MARKER_OPEN, CORTEX_MARKER_CLOSE)
}

pub fn has_marker_block_with(content: &str, open_marker: &str, close_marker: &str) -> bool {
    find_block(content, open_marker, close_marker).is_some()
}

struct Block {
    start: usize,
    end: usize,
}

/// Primer bloque completo (bytes), marcadores incluidos.
fn find_block(haystack: &str, open_marker: &str, close_marker: &str) -> Option<Block> {
    let bytes = haystack.as_bytes();
    let open_b = open_marker.as_bytes();
    let close_b = close_marker.as_bytes();
    let mut i = 0;
    while i + open_b.len() <= bytes.len() {
        if &bytes[i..i + open_b.len()] == open_b {
            let mut j = i + open_b.len();
            while j + close_b.len() <= bytes.len() {
                if &bytes[j..j + close_b.len()] == close_b {
                    return Some(Block {
                        start: i,
                        end: j + close_b.len(),
                    });
                }
                j += 1;
            }
            return None; // abierto sin cerrar
        }
        i += 1;
    }
    None
}

/// Todos los bloques verbatim (marcadores incluidos), en orden.
pub fn extract_marker_blocks(content: &str) -> Vec<String> {
    extract_marker_blocks_with(content, CORTEX_MARKER_OPEN, CORTEX_MARKER_CLOSE)
}

pub fn extract_marker_blocks_with(
    content: &str,
    open_marker: &str,
    close_marker: &str,
) -> Vec<String> {
    let mut out = Vec::new();
    let mut rest = content;
    let mut offset = 0usize;
    while let Some(b) = find_block(rest, open_marker, close_marker) {
        out.push(rest[b.start..b.end].to_string());
        offset += b.end;
        rest = &content[offset..];
    }
    out
}

/// `strip_marker_blocks`: elimina bloques preservando el resto byte-a-byte;
/// colapsa whitespace final sólo si removió algo. Idempotente.
pub fn strip_marker_blocks(content: &str) -> String {
    strip_marker_blocks_with(content, CORTEX_MARKER_OPEN, CORTEX_MARKER_CLOSE)
}

pub fn strip_marker_blocks_with(content: &str, open_marker: &str, close_marker: &str) -> String {
    if find_block(content, open_marker, close_marker).is_none() {
        return content.to_string();
    }
    let mut parts: Vec<&str> = Vec::new();
    let mut rest = content;
    loop {
        match find_block(rest, open_marker, close_marker) {
            None => {
                parts.push(rest);
                break;
            }
            Some(b) => {
                parts.push(&rest[..b.start]);
                let mut end = b.end;
                let bytes = rest.as_bytes();
                if end < bytes.len() && bytes[end] == b'\n' {
                    end += 1;
                }
                rest = &rest[end..];
            }
        }
    }
    let cleaned: String = parts.concat();
    if cleaned.trim().is_empty() {
        return String::new();
    }
    cleaned.trim_end().to_string() + "\n"
}

/// `upsert_marker_block` (semántica codex).
pub fn upsert_marker_block(content: &str, block: &str) -> String {
    upsert_marker_block_with(content, block, CORTEX_MARKER_OPEN, CORTEX_MARKER_CLOSE)
}

pub fn upsert_marker_block_with(
    content: &str,
    block: &str,
    open_marker: &str,
    close_marker: &str,
) -> String {
    let block_body = block.trim();
    let matches: Vec<Block> = {
        let mut v = Vec::new();
        let mut rest_offset = 0usize;
        let mut rest = content;
        while let Some(b) = find_block(rest, open_marker, close_marker) {
            v.push(Block {
                start: rest_offset + b.start,
                end: rest_offset + b.end,
            });
            rest_offset += b.end;
            rest = &content[rest_offset..];
        }
        v
    };
    if let (Some(first), Some(last)) = (matches.first(), matches.last()) {
        return format!(
            "{}{}{}",
            &content[..first.start],
            block_body,
            &content[last.end..]
        );
    }
    if content.is_empty() {
        return format!("{block_body}\n");
    }
    let sep = if content.ends_with('\n') {
        "\n"
    } else {
        "\n\n"
    };
    format!("{content}{sep}{block_body}\n")
}

/// `is_cortex_owned_file`.
pub fn is_cortex_owned_file(content: &str) -> bool {
    if content.trim().is_empty() {
        return false;
    }
    strip_marker_blocks(content).is_empty()
}

/// `is_content_identical_to_bundle` con normalización de CRLF + timestamps.
pub fn is_content_identical_to_bundle(content: &str, bundle: &str) -> bool {
    normalize_for_compare(content) == normalize_for_compare(bundle)
}

fn normalize_for_compare(text: &str) -> String {
    let no_crlf = text.replace("\r\n", "\n");
    // ^Last sync: .*$ → "Last sync: <timestamp>" (línea por línea).
    let mut normalized_lines: Vec<String> = Vec::new();
    for line in no_crlf.split('\n') {
        if line.starts_with("Last sync: ") {
            normalized_lines.push("Last sync: <timestamp>".to_string());
        } else {
            normalized_lines.push(line.to_string());
        }
    }
    normalized_lines.join("\n").trim().to_string()
}

