/// Detección de layout nuevo (workspace.yaml layout_version >= 2) reutilizada
/// por prompts.rs; espejo del Case 1 de WorkspaceLayout.discover.
pub fn is_new_layout(project_root: &Path) -> bool {
    let ws = project_root.join(".cortex").join("workspace.yaml");
    if ws.is_file() {
        if let Ok(content) = std::fs::read_to_string(&ws) {
            for line in content.lines() {
                if let Some(rest) = line.trim().strip_prefix("layout_version:") {
                    if rest.trim().parse::<i64>().map(|v| v >= 2).unwrap_or(false) {
                        return true;
                    }
                }
            }
        }
    }
    false
}
